/**
 * @file EmailExecutiveReportDispatcher.js
 * @description Formats and packages daily morning executive email reports (HTML & Text)
 * for brokerage managing directors and agency principals summarizing 24-hour KPIs.
 * Category: Integrations
 */

export class EmailExecutiveReportDispatcher {
  /**
   * Generates multipart HTML/Text email payload for daily briefing
   * @param {Object} metrics
   * @param {string} recipientEmail
   * @returns {Object} Structured email payload
   */
  compileEmailReport(metrics, recipientEmail = 'principals@agency.ae') {
    const {
      date = new Date().toISOString().split('T')[0],
      totalInquiries = 0,
      qualifiedLeads = 0,
      viewingsScheduled = 0,
      dealsClosed = 0,
      totalVolumeAed = 0
    } = metrics;

    const formattedVolume = Number(totalVolumeAed).toLocaleString('en-US');

    const subject = `[Daily Executive Briefing] Dubai Real Estate Operations - ${date}`;

    const textBody = [
      `Dubai Real Estate Daily Executive Briefing - ${date}`,
      `Total Inquiries: ${totalInquiries}`,
      `Qualified Leads: ${qualifiedLeads}`,
      `Viewings Scheduled: ${viewingsScheduled}`,
      `Deals Closed: ${dealsClosed}`,
      `Total Volume: AED ${formattedVolume}`,
      `\nReport generated by WhatsApp Bot Linda Operations Center.`
    ].join('\n');

    const htmlBody = `
      <div style="font-family: Arial, sans-serif; max-width: 600px; margin: auto; padding: 20px; border: 1px solid #e5e7eb; border-radius: 8px;">
        <h2 style="color: #1e3a8a; margin-bottom: 5px;">Daily Executive Briefing</h2>
        <p style="color: #6b7280; font-size: 14px;">Date: ${date}</p>
        <hr style="border: 0; border-top: 1px solid #e5e7eb; margin: 15px 0;" />
        <table style="width: 100%; border-collapse: collapse;">
          <tr><td style="padding: 8px 0;">Total Inquiries</td><td style="font-weight: bold; text-align: right;">${totalInquiries}</td></tr>
          <tr><td style="padding: 8px 0;">Qualified Leads</td><td style="font-weight: bold; text-align: right;">${qualifiedLeads}</td></tr>
          <tr><td style="padding: 8px 0;">Viewings Scheduled</td><td style="font-weight: bold; text-align: right;">${viewingsScheduled}</td></tr>
          <tr><td style="padding: 8px 0;">Deals Closed</td><td style="font-weight: bold; text-align: right;">${dealsClosed}</td></tr>
          <tr style="border-top: 2px solid #e5e7eb;"><td style="padding: 12px 0; font-weight: bold;">Total Sales Volume</td><td style="font-weight: bold; color: #059669; text-align: right;">AED ${formattedVolume}</td></tr>
        </table>
      </div>
    `.trim();

    return {
      to: recipientEmail,
      subject,
      text: textBody,
      html: htmlBody
    };
  }
}

export default new EmailExecutiveReportDispatcher();
